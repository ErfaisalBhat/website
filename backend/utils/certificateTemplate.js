// ---------- PDF rendering ----------

/**
 * Renders one certificate to a PDF file using Puppeteer.
 * @param {Object} data        Student/certificate data.
 * @param {string} bgImagePath Absolute path to Blue.png.
 * @param {string} outputPath  Where to write the resulting PDF.
 */
async function generateCertificatePDF(data, bgImagePath, outputPath) {
  const html = generateCertificateHTML(data, bgImagePath);

  const browser = await puppeteer.launch({
    headless: 'new',
    args: ['--no-sandbox', '--disable-setuid-sandbox'],
  });
  try {
    const page = await browser.newPage();
    await page.setContent(html, { waitUntil: 'networkidle0' });
    await page.pdf({
      path: outputPath,
      format: 'A4',
      printBackground: true,
      margin: { top: '0mm', bottom: '0mm', left: '0mm', right: '0mm' },
    });
  } finally {
    await browser.close();
  }
  return outputPath;
}

/**
 * Generates certificates for many students in one call.
 * @param {Object[]} studentsData Array of student data objects.
 * @param {string} bgImagePath    Absolute path to Blue.png.
 * @param {string} outDir         Directory to write PDFs into.
 * @returns {Promise<string[]>}   Array of generated file paths.
 */
async function generateBulkCertificates(studentsData, bgImagePath, outDir) {
  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

  const browser = await puppeteer.launch({
    headless: 'new',
    args: ['--no-sandbox', '--disable-setuid-sandbox'],
  });

  const outputPaths = [];
  try {
    for (const data of studentsData) {
      const html = generateCertificateHTML(data, bgImagePath);
      const page = await browser.newPage();
      await page.setContent(html, { waitUntil: 'networkidle0' });

      const fileName = `${data.rollNo}_${(data.candidateName || '').replace(/\s+/g, '_')}_Diploma.pdf`;
      const outputPath = path.join(outDir, fileName);

      await page.pdf({
        path: outputPath,
        format: 'A4',
        printBackground: true,
        margin: { top: '0mm', bottom: '0mm', left: '0mm', right: '0mm' },
      });

      await page.close();
      outputPaths.push(outputPath);
    }
  } finally {
    await browser.close();
  }
  return outputPaths;
}

