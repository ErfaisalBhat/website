/**
 * certificateTemplate.js
 *
 * Generates a Diploma / Statement-of-Marks certificate as HTML and PDF,
 * using Blue.png as the certificate background/border, replicating the
 * layout of DIPLOMA_CERTIFICTAE.docx.
 *
 * Usage:
 *   const { generateCertificatePDF } = require('./certificateTemplate');
 *
 *   await generateCertificatePDF(studentData, '/path/to/Blue.png', '/path/to/output.pdf');
 *
 * studentData shape (matches the CSV template fields):
 * {
 *   rollNo, candidateName, fatherName, courseName, semester, part,
 *   examSession, examFlag, academicYear, dateOfResult,
 *   certificateNumber,               // unique cert no, generated by caller
 *   papers: [                        // exactly 6 entries expected
 *     { code, name, ia, th, prpw, result },
 *     ...
 *   ],
 *   totalMax, totalObtained, division
 * }
 */

const fs = require('fs');
const path = require('path');
const puppeteer = require('puppeteer');

// ---------- helpers ----------

/** Reads Blue.png from disk and returns a base64 data-URI so the HTML is self-contained. */
function imageToDataUri(imagePath) {
  const ext = path.extname(imagePath).slice(1) || 'png';
  const buffer = fs.readFileSync(imagePath);
  return `data:image/${ext};base64,${buffer.toString('base64')}`;
}

/** Renders a mark cell; blank/undefined marks are shown as "-" (not "0" or "N/A"). */
function fmtMark(val) {
  if (val === undefined || val === null || val === '') return '-';
  return String(val);
}

/** Escapes basic HTML special chars in user-supplied text fields. */
function esc(str) {
  if (str === undefined || str === null) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/** Builds the 6 subject rows of the marks table. */
function buildPaperRows(papers = []) {
  const rows = [];
  for (let i = 0; i < 6; i++) {
    const p = papers[i] || {};
    rows.push(`
      <tr>
        <td class="sr">${i + 1}.</td>
        <td class="code">${esc(p.code)}</td>
        <td class="name">${esc(p.name)}</td>
        <td class="sem">${esc(p.sem || '')}</td>
        <td class="mark">${fmtMark(p.ia)}</td>
        <td class="mark">${fmtMark(p.th)}</td>
        <td class="mark">${fmtMark(p.prpw)}</td>
        <td class="result">${esc(p.result || '')}</td>
      </tr>`);
  }
  return rows.join('\n');
}

// ---------- main HTML builder ----------

function fontToDataUri(fontPath) {
  try {
    const buffer = fs.readFileSync(fontPath);
    return `data:font/ttf;base64,${buffer.toString('base64')}`;
  } catch(e) {
    console.error("Font not found at", fontPath);
    return '';
  }
}

